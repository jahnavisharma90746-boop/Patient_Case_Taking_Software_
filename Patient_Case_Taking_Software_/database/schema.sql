-- ============================================================================
-- 1. PRIMARY APP TABLE (DIRECT FRONTEND COMPATIBILITY)
-- Matches exact table name and schema used in script.js:
--   db.from("Appoinments").insert([patientData])
--   db.from("Appoinments").select("*").order("id", { ascending: false })
-- ============================================================================

CREATE TABLE IF NOT EXISTS public."Appoinments" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT DEFAULT '',
    date DATE DEFAULT CURRENT_DATE,
    message TEXT,
    status TEXT DEFAULT 'Pending' CHECK (status IN ('Pending', 'Verified', 'Review', 'Completed')),
    is_emergency BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index for ordering & searching in Doctor Dashboard
CREATE INDEX IF NOT EXISTS idx_appoinments_id_desc ON public."Appoinments" (id DESC);
CREATE INDEX IF NOT EXISTS idx_appoinments_status ON public."Appoinments" (status);
CREATE INDEX IF NOT EXISTS idx_appoinments_name ON public."Appoinments" (name);

-- ============================================================================
-- 2. NORMALIZED PRODUCTION RELATIONAL SCHEMA
-- For enterprise medical case management, analytics, and doctor portals
-- ============================================================================

-- 2.1 Doctors
CREATE TABLE IF NOT EXISTS public.doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE,
    phone TEXT,
    specialization TEXT DEFAULT 'General Physician',
    license_number TEXT UNIQUE,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.2 Patients
CREATE TABLE IF NOT EXISTS public.patients (
    patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    age INTEGER,
    gender TEXT CHECK (gender IN ('Male', 'Female', 'Other', 'Not specified')),
    phone TEXT,
    email TEXT,
    preferred_language VARCHAR(5) DEFAULT 'en' CHECK (preferred_language IN ('en', 'hi')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.3 Patient Cases / Clinical Encounters
CREATE TABLE IF NOT EXISTS public.patient_cases (
    case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT REFERENCES public.patients(patient_id) ON DELETE CASCADE,
    assigned_doctor_id BIGINT REFERENCES public.doctors(doctor_id) ON DELETE SET NULL,
    appointment_id BIGINT REFERENCES public."Appoinments"(id) ON DELETE SET NULL,
    case_date DATE DEFAULT CURRENT_DATE NOT NULL,
    status TEXT DEFAULT 'Pending' CHECK (status IN ('Pending', 'Verified', 'Review', 'Completed', 'Cancelled')),
    is_priority_alert BOOLEAN DEFAULT FALSE,
    urgency_level TEXT DEFAULT 'Routine' CHECK (urgency_level IN ('Routine', 'Moderate', 'Priority', 'Critical')),
    doctor_notes TEXT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.4 Clinical Assessments (Structured Questionnaire Answers)
CREATE TABLE IF NOT EXISTS public.clinical_assessments (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES public.patient_cases(case_id) ON DELETE CASCADE,
    chief_complaint TEXT NOT NULL,
    duration TEXT,
    medical_history TEXT,
    current_medications TEXT,
    allergies TEXT DEFAULT 'None reported',
    recorded_language VARCHAR(5) DEFAULT 'en',
    ai_generated_summary TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.5 Medical Documents & Reports (Prescriptions, Lab Reports)
CREATE TABLE IF NOT EXISTS public.medical_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES public.patient_cases(case_id) ON DELETE CASCADE,
    file_name TEXT NOT NULL,
    file_type TEXT,
    file_size_bytes BIGINT,
    storage_url TEXT,
    analysis_status TEXT DEFAULT 'Uploaded' CHECK (analysis_status IN ('Uploaded', 'Processing', 'Analyzed', 'Failed')),
    analysis_extracted_text TEXT,
    uploaded_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.6 Emergency Triage Alerts
CREATE TABLE IF NOT EXISTS public.emergency_alerts (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES public.patient_cases(case_id) ON DELETE CASCADE,
    trigger_keyword TEXT NOT NULL,
    severity_level TEXT DEFAULT 'High' CHECK (severity_level IN ('Moderate', 'High', 'Critical')),
    is_acknowledged BOOLEAN DEFAULT FALSE,
    acknowledged_by BIGINT REFERENCES public.doctors(doctor_id),
    acknowledged_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ============================================================================
-- 3. AUTOMATIC PARSER TRIGGER: Sync "Appoinments" to Normalized Schema
-- Parses: Age, Health Problem, Duration, Medical History, Medicines from message
-- ============================================================================

CREATE OR REPLACE FUNCTION public.parse_appointment_to_case()
RETURNS TRIGGER AS $$
DECLARE
    v_age INTEGER := NULL;
    v_complaint TEXT := 'Not specified';
    v_duration TEXT := 'Not specified';
    v_history TEXT := 'None reported';
    v_medicines TEXT := 'None reported';
    v_patient_id BIGINT;
    v_case_id BIGINT;
    v_is_emergency BOOLEAN := FALSE;
BEGIN
    -- Extract fields using regex from message text
    BEGIN
        v_age := NULLIF(substring(NEW.message FROM 'Age:\s*([0-9]+)'), '')::INTEGER;
    EXCEPTION WHEN OTHERS THEN
        v_age := NULL;
    END;

    v_complaint := COALESCE(NULLIF(trim(substring(NEW.message FROM 'Health Problem:\s*([^\n\r]+)')), ''), 'Not specified');
    v_duration := COALESCE(NULLIF(trim(substring(NEW.message FROM 'Duration:\s*([^\n\r]+)')), ''), 'Not specified');
    v_history := COALESCE(NULLIF(trim(substring(NEW.message FROM 'Medical History:\s*([^\n\r]+)')), ''), 'None reported');
    v_medicines := COALESCE(NULLIF(trim(substring(NEW.message FROM 'Medicines:\s*([^\n\r]+)')), ''), 'None reported');

    -- Emergency keyword triage check
    IF LOWER(v_complaint) ~* '(chest pain|difficulty breathing|breathing problem|unconscious|severe bleeding|stroke|heart attack|सीने में दर्द|सांस लेने में दिक्कत|बेहोशी|बहुत ज्यादा खून|हार्ट अटैक)' THEN
        v_is_emergency := TRUE;
        NEW.is_emergency := TRUE;
    END IF;

    -- Upsert/insert patient
    INSERT INTO public.patients (full_name, age, phone)
    VALUES (NEW.name, v_age, NEW.phone)
    RETURNING patient_id INTO v_patient_id;

    -- Create patient case
    INSERT INTO public.patient_cases (
        patient_id,
        appointment_id,
        case_date,
        status,
        is_priority_alert,
        urgency_level
    ) VALUES (
        v_patient_id,
        NEW.id,
        COALESCE(NEW.date, CURRENT_DATE),
        COALESCE(NEW.status, 'Pending'),
        v_is_emergency,
        CASE WHEN v_is_emergency THEN 'Critical' ELSE 'Routine' END
    ) RETURNING case_id INTO v_case_id;

    -- Create clinical assessment
    INSERT INTO public.clinical_assessments (
        case_id,
        chief_complaint,
        duration,
        medical_history,
        current_medications,
        ai_generated_summary
    ) VALUES (
        v_case_id,
        v_complaint,
        v_duration,
        v_history,
        v_medicines,
        NEW.message
    );

    -- If emergency, create alert record
    IF v_is_emergency THEN
        INSERT INTO public.emergency_alerts (
            case_id,
            trigger_keyword,
            severity_level
        ) VALUES (
            v_case_id,
            v_complaint,
            'Critical'
        );
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_parse_appointment ON public."Appoinments";
CREATE TRIGGER trg_parse_appointment
AFTER INSERT ON public."Appoinments"
FOR EACH ROW
EXECUTE FUNCTION public.parse_appointment_to_case();

-- ============================================================================
-- 4. VIEWS FOR DOCTOR DASHBOARD & STATS
-- ============================================================================

CREATE OR REPLACE VIEW public.v_doctor_dashboard AS
SELECT 
    a.id AS appointment_id,
    a.name AS patient_name,
    COALESCE(p.age::TEXT, substring(a.message FROM 'Age:\s*([^\n\r]+)'), '—') AS age,
    COALESCE(ca.chief_complaint, substring(a.message FROM 'Health Problem:\s*([^\n\r]+)'), '—') AS complaint,
    a.status,
    COALESCE(a.is_emergency, pc.is_priority_alert, FALSE) AS is_priority_alert,
    a.date AS appointment_date,
    a.created_at
FROM public."Appoinments" a
LEFT JOIN public.patient_cases pc ON pc.appointment_id = a.id
LEFT JOIN public.patients p ON p.patient_id = pc.patient_id
LEFT JOIN public.clinical_assessments ca ON ca.case_id = pc.case_id
ORDER BY a.id DESC;

CREATE OR REPLACE VIEW public.v_dashboard_stats AS
SELECT
    COUNT(*) AS total_patients,
    COUNT(*) FILTER (WHERE status = 'Pending') AS pending_cases,
    COUNT(*) FILTER (WHERE status = 'Verified') AS verified_cases,
    COUNT(*) FILTER (WHERE is_emergency = TRUE OR status = 'Review') AS priority_alerts
FROM public."Appoinments";

